#!/usr/bin/env python3
"""Assemble a self-contained static svg-bench site for GitHub Pages.

Usage:
    python3 build_site.py                 # -> svg-bench/_site
    python3 build_site.py --out _site     # custom output directory

The deployed tree looks like:

    _site/
      index.html  style.css  app.js  config.js  data.json  data.js
      results/<task>/<artifact>.svg
      .nojekyll

`results/` is copied next to the page so the relative `results/...` URLs in
data.json work on GitHub Pages, including project sites served from a
subdirectory. No logs, sidecars, prompts or Python files are published.

Supabase configuration can be injected at build time instead of being committed:

    SUPABASE_URL=https://xxxx.supabase.co \
    SUPABASE_ANON_KEY=... \
    SUPABASE_REVIEWS_TABLE=svgbench_reviews \
    python3 build_site.py
"""
import argparse
import json
import os
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.abspath(__file__))
SITE = os.path.join(ROOT, 'site')
RESULTS = os.path.join(ROOT, 'results')


def copy_file(src, dst):
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    shutil.copy2(src, dst)


def write_config(out_dir):
    """Write site/config.js, using env vars when provided.

    The Supabase anon key is intentionally public (it is shipped to browsers);
    row-level security in supabase.sql is what protects the table.
    """
    url = (os.environ.get('SUPABASE_URL') or '').strip()
    key = (os.environ.get('SUPABASE_ANON_KEY') or '').strip()
    table = (os.environ.get('SUPABASE_REVIEWS_TABLE') or 'svgbench_reviews').strip()
    if not url or not key:
        src = os.path.join(SITE, 'config.js')
        if os.path.isfile(src):
            copy_file(src, os.path.join(out_dir, 'config.js'))
            return
        url, key = '', ''
    body = (
        '/* Generated by build_site.py. The anon key is public by design. */\n'
        'window.SVG_BENCH_CONFIG = ' +
        json.dumps({
            'supabase': {'url': url, 'anonKey': key, 'table': table},
        }, indent=2) + ';\n'
    )
    with open(os.path.join(out_dir, 'config.js'), 'w', encoding='utf-8') as fh:
        fh.write(body)


def write_data(out_dir):
    """Rewrite artifact URLs for the deployed layout.

    The checked-in site/data.json uses ../results/... so it also works from a
    file:// checkout and through serve.py. The built site places artifacts at
    <site>/results/, so strip the leading ../ for GitHub Pages.
    """
    data = json.load(open(os.path.join(SITE, 'data.json'), encoding='utf-8'))
    for run in data.get('runs', []):
        rel = run.get('svg_rel')
        if isinstance(rel, str) and rel.startswith('../'):
            run['svg_rel'] = rel[3:]
    with open(os.path.join(out_dir, 'data.json'), 'w', encoding='utf-8') as fh:
        json.dump(data, fh, indent=1)
    with open(os.path.join(out_dir, 'data.js'), 'w', encoding='utf-8') as fh:
        fh.write('window.__SVG_BENCH__ = ')
        json.dump(data, fh, separators=(',', ':'))
        fh.write(';')


def build(out_dir):
    out_dir = os.path.abspath(out_dir)
    # Never let a mis-typed --out wipe the repo or its parent.
    if out_dir in (ROOT, os.path.dirname(ROOT)) or not out_dir.startswith(ROOT + os.sep):
        sys.exit(f"refusing to build into {out_dir!r}; choose a directory under {ROOT!r}")
    if out_dir == SITE or out_dir.startswith(SITE + os.sep):
        sys.exit("refusing to build into svg-bench/site; choose another directory")

    subprocess.run([sys.executable, os.path.join(ROOT, 'leaderboard.py')], check=True)

    if os.path.isdir(out_dir):
        shutil.rmtree(out_dir)
    os.makedirs(out_dir)

    for name in ('index.html', 'style.css', 'app.js'):
        copy_file(os.path.join(SITE, name), os.path.join(out_dir, name))
    write_data(out_dir)
    write_config(out_dir)

    if os.path.isfile(os.path.join(SITE, 'reviews.json')):
        copy_file(os.path.join(SITE, 'reviews.json'), os.path.join(out_dir, 'reviews.json'))

    published = 0
    for dirpath, _dirnames, filenames in os.walk(RESULTS):
        for fn in filenames:
            if not fn.lower().endswith('.svg'):
                continue
            src = os.path.join(dirpath, fn)
            rel = os.path.relpath(src, RESULTS)
            copy_file(src, os.path.join(out_dir, 'results', rel))
            published += 1

    open(os.path.join(out_dir, '.nojekyll'), 'wb').close()
    print(f"build_site: wrote {out_dir} — {published} SVG artifact(s)")


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument('--out', default=os.path.join(ROOT, '_site'),
                    help='output directory (default: svg-bench/_site)')
    args = ap.parse_args()
    build(args.out)


if __name__ == '__main__':
    main()
